class Solution:
    def threeSum(self, nums: list[int]) -> list[list[int]]:
        nums.sort()
        # print("nums", nums)
        result = []
        if len(nums) < 3:
            return result

        for fixed in range(len(nums)):
            if fixed > 0 and nums[fixed] == nums[fixed - 1]:
                continue
            if nums[fixed] > 0:
                break
            left = fixed + 1
            right = len(nums) - 1
            while left < right:
                total = nums[fixed] + nums[left] + nums[right]
                if total == 0:

                    # if [nums[fixed], nums[left], nums[right]] not in result:
                    result.append([nums[fixed], nums[left], nums[right]])
                    curr_left = nums[left]
                    curr_right = nums[right]
                    left += 1
                    right -= 1

                    if curr_left == nums[left]:
                        while nums[left] == curr_left:
                            left += 1
                            if left >= right:
                                break
                    if curr_right == nums[right]:
                        while nums[right] == curr_right:
                            right -= 1
                            if right <= left:
                                break
                elif total < 0:
                    left += 1
                elif total > 0:
                    right -= 1

        return result


